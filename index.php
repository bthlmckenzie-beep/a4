      <div class="container">
        <div class="section-header">
          <span class="badge-tag">Frequently Answered</span>
          <h2 class="section-title">Technical Outerwear & Layering Inquiries</h2>
          <p class="section-subtitle">Understanding membrane breathability ratings, down fill-power metrics, and waterproof jacket care.</p>
        </div>

        <div class="accordion-wrapper">
          <div class="accordion-item active">
            <button class="accordion-header">
              <span>What is Hydrostatic Head and why does 20,000mm matter for technical hard shells?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              Hydrostatic Head (measured in millimeters of water column, mm H&sup2;O) measures the liquid water pressure a fabric can withstand before moisture penetrates. While light rain exerts approximately 1,500mm of pressure, a heavy backpack strap, direct kneeling in wet snow, or gale-force mountain winds can exert localized pressures exceeding 15,000mm to 20,000mm. A 20,000mm to 30,000mm rating guarantees total stormproof protection under sustained physical load.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>What is the difference between RET and MVTR breathability ratings?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              MVTR (Moisture Vapor Transmission Rate) measures how many grams of water vapor pass through one square meter of fabric in 24 hours (g/m&sup2;/24h)—where higher numbers indicate greater breathability. RET (Resistance to Evaporative Heat Transfer, ISO 11092) measures how much a textile resists moisture vapor—where lower numbers indicate superior breathability. A hard shell with RET &lt; 6 or MVTR &gt; 20,000 g/m&sup2;/24h is considered extremely breathable for high-output mountaineering.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>How does box-wall baffle construction prevent cold spots in down jackets?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              In cheap "stitch-through" down jackets, the exterior fabric and inner lining are sewn directly together along seam lines. Along those stitch lines, there is zero down insulation, creating continuous channels for wind and thermal heat loss. In contrast, authentic 3D box-wall baffle construction uses vertical mesh fabric walls between the outer shell and lining, creating cubic compartments that allow down clusters to loft to their full volume with zero compressed cold spots.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>How should technical waterproof jackets be washed and reproofed?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              Never use standard household laundry detergents or fabric softeners, as their chemical surfactants leave hydrophilic residues that clog membrane micropores and destroy DWR water beading. Instead, wash technical jackets with specialized pH-neutral technical cleaners (such as Nikwax Tech Wash or Grangers Performance Wash), followed by tumble drying on low heat for 20 minutes to thermally reactivate the fluorocarbon-free DWR coating.
            </div>
          </div>
        </div>
